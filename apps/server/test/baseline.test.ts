import { describe, expect, it } from "vitest";
import { FormModel, Snapshot } from "@blip/protocol";
import { loadFormModelGolden, loadSnapshot } from "@blip/protocol/fixtures-loader";
import { buildBaselineFormModel } from "../src/baseline/index";

/** Warm up once, then the best (minimum) of 5 timed runs, in milliseconds. */
function bestOf5(run: () => unknown): number {
  run();
  let best = Infinity;
  for (let i = 0; i < 5; i++) {
    const t0 = performance.now();
    run();
    best = Math.min(best, performance.now() - t0);
  }
  return best;
}

describe("buildBaselineFormModel: booking tracer", () => {
  it("booking fixture parses with the Snapshot schema", () => {
    expect(Snapshot.safeParse(loadSnapshot("booking")).success).toBe(true);
  });

  it("deep-equals the committed golden (generated by the builder, not hand-written)", () => {
    const built = buildBaselineFormModel(loadSnapshot("booking"));
    expect(built).toEqual(loadFormModelGolden());
  });

  it("returns a schema-valid FormModel", () => {
    const built = buildBaselineFormModel(loadSnapshot("booking"));
    expect(FormModel.safeParse(built).success).toBe(true);
  });

  it("has the contracted shape: 9 fields (6 required), 3 actions, primary only on e10", () => {
    const m = buildBaselineFormModel(loadSnapshot("booking"));
    expect(m.fields).toHaveLength(9);
    expect(m.fields.filter((f) => f.required).map((f) => f.id)).toEqual(["e1", "e2", "e4", "e5", "e6", "e9"]);
    expect(m.actions).toHaveLength(3);
    expect(m.actions.filter((a) => a.primary).map((a) => a.id)).toEqual(["e10"]);
    expect(m.groups.map((g) => g.name)).toEqual(["Guest details", "Stay", "Payment"]);
    const card = m.fields.find((f) => f.id === "e9")!;
    expect(card.value).toBeNull();
    expect(card.hasValue).toBe(false);
    expect(m.repairStatus).toBe("baseline");
  });

  it("builds in under 100 ms (warm-up, best of 5)", () => {
    const snap = loadSnapshot("booking");
    expect(bestOf5(() => buildBaselineFormModel(snap))).toBeLessThan(100);
  });

  it("is deterministic and does not mutate its input", () => {
    const snap = loadSnapshot("booking");
    const before = structuredClone(snap);
    const a = buildBaselineFormModel(snap);
    const b = buildBaselineFormModel(snap);
    expect(a).toEqual(b);
    expect(snap).toEqual(before);
  });
});
