/** Warm up once, then the best (minimum) of 5 timed runs, in milliseconds. */
function bestOf5(run: () => unknown): number {
  run();
  let best = Infinity;
  for (let i = 0; i < 5; i++) {
    const t0 = performance.now();
    run();
    best = Math.min(best, performance.now() - t0);
  }
  return best;
}

