describe("performance (PAGE-02, under 100 ms)", () => {
  it.each(FIXTURE_NAMES)("fixture %s builds in under 100 ms (warm-up, best of 5)", (name) => {
    const snap = loadSnapshot(name);
    expect(bestOf5(() => buildBaselineFormModel(snap))).toBeLessThan(100);
  });

  it("a synthetic 250-element snapshot builds in under 100 ms and is schema-valid", () => {
    const booking = loadSnapshot("booking");
    const elements = Array.from({ length: 250 }, (_, i) => ({
      ...structuredClone(booking.elements[i % booking.elements.length]!),
      id: `e${i + 1}`,
      order: i + 1,
    }));
    const synthetic = Snapshot.parse({ ...booking, elements });
    expect(synthetic.elements).toHaveLength(250);
    expect(bestOf5(() => buildBaselineFormModel(synthetic))).toBeLessThan(100);
    expect(FormModel.safeParse(buildBaselineFormModel(synthetic)).success).toBe(true);
  });
});
